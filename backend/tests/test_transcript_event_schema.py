"""The session subscription's envelope contract (docs/design/transcript-event.schema.json).

What is tested:
- every envelope the REAL backend produced in the liveReload fixture (turn events,
  replays, resyncs, transcript feed rows, state pushes and snapshots, background
  agent updates — generated by tests/test_live_reload_scenarios.py on the real
  backend and real SQLite) validates against the schema;
- the fixture exercises every type the schema details, except the ones listed
  with the reason they do not occur there (so a type silently dropped from the
  backend is noticed);
- every type the schema details is consumed by name in the desktop sources that
  render the subscription, and produced by name in the backend: the schema
  cannot drift into describing a type nobody sends or reads.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import jsonschema   # installed with claude-agent-sdk (a pinned runtime dependency)

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = json.loads((ROOT / "docs/design/transcript-event.schema.json").read_text(encoding="utf-8"))
FIXTURE = ROOT / "desktop/src/__tests__/fixtures/liveReload/scenarios.json"
DESKTOP = [ROOT / "desktop/src" / p for p in (
    "services/sessionEvents.ts", "hooks/sessionTurnRouter.ts", "hooks/transcriptFeed.ts",
    "hooks/useChatStreamingLifecycle.ts")]

#: detailed types the fixture does not produce, and why
NOT_IN_FIXTURE = {
    "transcript_delete": "no scenario deletes a row (tests/test_transcript_feed covers it)",
}


def _detailed() -> set[str]:
    return {k for k in SCHEMA["$defs"] if k not in ("inTurn", "outsideTurn")}


def _envelopes():
    data = json.loads(FIXTURE.read_text(encoding="utf-8"))
    for s in data["scenarios"]:
        for st in s["steps"]:
            for env in [st.get("env"), *st.get("envs", [])]:
                if isinstance(env, dict) and "sessionId" in env and "eventSeq" in env:
                    yield s["sid"] if "sid" in s else "?", env


def test_every_fixture_envelope_validates():
    validator = jsonschema.Draft202012Validator(SCHEMA)
    seen, bad = set(), []
    for sid, env in _envelopes():
        seen.add(env["type"])
        errs = sorted(validator.iter_errors(env), key=lambda e: list(e.path))
        if errs:
            bad.append(f"{sid} {env['type']}#{env['eventSeq']}: {errs[0].message}")
    assert not bad, bad[:10]
    missing = _detailed() - seen - set(NOT_IN_FIXTURE)
    assert not missing, f"schema types the real backend never produced in the fixture: {missing}"


def test_the_schema_rejects_a_broken_envelope():
    validator = jsonschema.Draft202012Validator(SCHEMA)
    good = {"type": "transcript_row", "sessionId": "s", "eventSeq": 3, "turnId": "",
            "row": {"id": "r", "role": "user", "content": []}, "rev": 4, "op": "insert"}
    assert validator.is_valid(good)
    assert not validator.is_valid({**good, "turnId": "t1"})          # a feed row is outside any turn
    assert not validator.is_valid({**good, "rev": 0})
    assert not validator.is_valid({k: v for k, v in good.items() if k != "row"})
    assert not validator.is_valid({"type": "turn_start", "sessionId": "s", "eventSeq": 1, "turnId": "t", "source": "x"})


def test_every_detailed_type_is_produced_by_the_backend_and_consumed_by_the_desktop():
    desktop = "\n".join(p.read_text(encoding="utf-8") for p in DESKTOP)
    backend = "\n".join(p.read_text(encoding="utf-8", errors="replace")
                        for p in (ROOT / "backend").rglob("*.py")
                        if ".venv" not in p.parts and "tests" not in p.parts)
    unread = [t for t in _detailed() if not re.search(rf"""['"]{t}['"]""", desktop)]
    unsent = [t for t in _detailed() if not re.search(rf"""['"]{t}['"]""", backend)]
    assert not unread, f"schema types no desktop subscription code reads: {unread}"
    assert not unsent, f"schema types no backend code produces: {unsent}"
