#!/usr/bin/env python3
"""gen_expert_catalog — write the expert-review skill's CATALOG.md from the experts' frontmatter.

Design docs/design/2026-10-24-swarmai-usable-by-anyone.md §3.5: the catalog the agent
reads in native mode is generated from backend/experts/<domain>/<id>.md, so adding an
expert means adding its file and re-running this script (tests/test_expert_catalog.py
fails while CATALOG.md is stale). Only ``visibility: public`` experts are listed.

Usage: python backend/scripts/gen_expert_catalog.py [--check]
Public: ``render()``.
"""
from __future__ import annotations

import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))
OUT = BACKEND / "skills" / "s_expert-review" / "CATALOG.md"


def render() -> str:
    from core.expert_manager import ExpertManager
    experts = ExpertManager(BACKEND / "experts").scan_experts()
    rows = []
    for eid in sorted(experts):
        info = experts[eid]
        if str(getattr(info, "visibility", "public")).lower() != "public":
            continue
        domain = getattr(info, "domain", "") or "code"
        rows.append(f"| `{eid}` | {info.display_name_zh} / {info.display_name_en} | "
                    f"{getattr(info, 'scope', '')} | `../../experts/{domain}/{eid}.md` |")
    return ("<!-- GENERATED by backend/scripts/gen_expert_catalog.py from "
            "backend/experts/*/*.md — do not edit by hand -->\n"
            "# Expert catalog\n\n"
            "Prompt paths are relative to this skill's base directory.\n\n"
            "| id | name | scope | prompt file |\n|---|---|---|---|\n"
            + "\n".join(rows) + "\n")


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is stale: run python backend/scripts/gen_expert_catalog.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
